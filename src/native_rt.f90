	call v%push('    free(idx);')
	call v%push('}')
	call v%push('')
	call v%push('/* a[subs], where a is an array of strs, and the last of the rank + 1 subscripts is')
	call v%push(' * a substring of each of the elements that the others select.  The result has')
	call v%push(' * the shape of a slice, which is a single element if they are all scalars */')
	call v%push('sy_arr *sy_arr_str_sub(const sy_arr *a, const sy_sub *subs)')
