	call v%push('    if (rhs != NULL && rhs->len != w.total) {')
	call v%push('        sy_walk_free(&w);')
	call v%push('        sy_fatal("size of RHS does not match size of LHS slice");')
	call v%push('    }')
	call v%push('    if (rhs == a) rhs = tmp = sy_arr_dup(a);')
	call v%push('')
	call v%push('    for (t = 0; t < w.total; t++) {')
	call v%push('        lin = sy_walk_next(&w);')
	call v%push('        if (a->elem == SY_STR) {')
	call v%push('            sy_str *src = rhs != NULL ? ((sy_str **)rhs->data)[t] : *(sy_str *const *)scalar;')
	call v%push('')
	call v%push('            sy_str_free(((sy_str **)a->data)[lin]);')
	call v%push('            ((sy_str **)a->data)[lin] = sy_str_dup(src);')
	call v%push('        } else {')
	call v%push('            memcpy(a->data + (size_t)lin * es,')
	call v%push('                rhs != NULL ? rhs->data + (size_t)t * es : (const char *)scalar, es);')
	call v%push('        }')
	call v%push('    }')
	call v%push('    sy_arr_free(tmp);')
	call v%push('    sy_walk_free(&w);')
	call v%push('}')
	call v%push('')
	call v%push('/* The i-th character of s, for iterating over it */')
	call v%push('sy_str *sy_str_at(const sy_str *s, int64_t i)')
	call v%push('{')
	call v%push('    return sy_str_from(s->data + i, 1);')
	call v%push('}')
	call v%push('')
	call v%push('/* s[sub], a character or a substring */')
	call v%push('sy_str *sy_str_sub(const sy_str *s, const sy_sub *sub)')
	call v%push('{')
	call v%push('    int64_t cnt, i;')
	call v%push('    int64_t *idx = sy_sub_idx(sub, s->len, &cnt);')
	call v%push('    sy_str *r = sy_str_alloc(cnt);')
	call v%push('')
	call v%push('    for (i = 0; i < cnt; i++) r->data[i] = s->data[idx[i]];')
	call v%push('    free(idx);')
	call v%push('    return r;')
	call v%push('}')
	call v%push('')
	call v%push('/* s[sub] = rhs, where `slot` is the variable that holds s.  A string is only')
	call v%push(' * changed in place if it isn''t a literal, otherwise the variable gets a copy.')
	call v%push(' * The rhs of a single character or a range is truncated or padded with blanks')
	call v%push(' * to the length of the substring, like an assignment to a substring is in')
	call v%push(' * Fortran.  Otherwise it must be as long as the number of characters */')
	call v%push('void sy_str_set(sy_str **slot, const sy_sub *sub, const sy_str *rhs)')
	call v%push('{')
	call v%push('    sy_str *s = *slot;')
	call v%push('    int64_t cnt, i;')
	call v%push('    int64_t *idx = sy_sub_idx(sub, s->len, &cnt);')
	call v%push('    int fill = sub->kind == SUB_SCALAR || sub->kind == SUB_RANGE || sub->kind == SUB_ALL;')
	call v%push('')
	call v%push('    if (!fill && rhs->len != cnt) {')
	call v%push('        free(idx);')
	call v%push('        sy_fatal("size of RHS does not match size of LHS slice");')
	call v%push('    }')
	call v%push('    if (s->imm) s = *slot = sy_str_from(s->data, s->len);')
	call v%push('    for (i = 0; i < cnt; i++) s->data[idx[i]] = i < rhs->len ? rhs->data[i] : '' '';')
	call v%push('    free(idx);')
	call v%push('}')
	call v%push('')
	call v%push('/*============================================================================*/')
	call v%push('')
	call v%push('typedef struct {')
	call v%push('    char *p;')
	call v%push('    size_t n, cap;')
	call v%push('} sy_buf;')
	call v%push('')
	call v%push('static void sy_buf_put(sy_buf *b, const char *s, size_t n)')
	call v%push('{')
	call v%push('    if (b->n + n + 1 > b->cap) {')
	call v%push('        b->cap = 2 * (b->n + n + 1);')
	call v%push('        b->p = (char *)realloc(b->p, b->cap);')
	call v%push('        if (b->p == NULL) sy_fatal("out of memory");')
	call v%push('    }')
	call v%push('    memcpy(b->p + b->n, s, n);')
	call v%push('    b->n += n;')
	call v%push('}')
	call v%push('')
	call v%push('/* str(array), which is rt_join() of the Fortran runtime.  The elements are')
	call v%push(' * separated by ", ".  A rank > 1 array starts and ends with a line break, and')
	call v%push(' * has one after every complete row (and plane, etc.).  The elements of a float')
	call v%push(' * array are trimmed, unlike a scalar''s */')
	call v%push('sy_str *sy_arr_str(const sy_arr *a)')
	call v%push('{')
	call v%push('    sy_buf b = {NULL, 0, 0};')
	call v%push('    char tmp[40];')
	call v%push('    const char *p;')
	call v%push('    int64_t i, prod;')
	call v%push('    int32_t j;')
	call v%push('    size_t n;')
	call v%push('    sy_str *s;')
	call v%push('')
	call v%push('    sy_buf_put(&b, "[", 1);')
	call v%push('    if (a != NULL && a->rank > 1) sy_buf_put(&b, "\n", 1);')
	call v%push('')
	call v%push('    for (i = 0; a != NULL && i < a->len; i++) {')
	call v%push('        p = tmp;')
	call v%push('        switch (a->elem) {')
	call v%push('        case SY_I32:')
	call v%push('            n = (size_t)snprintf(tmp, sizeof tmp, "%d", (int)((int32_t *)a->data)[i]);')
	call v%push('            break;')
	call v%push('        case SY_I64:')
	call v%push('            n = (size_t)snprintf(tmp, sizeof tmp, "%lld", (long long)((int64_t *)a->data)[i]);')
	call v%push('            break;')
	call v%push('        case SY_F32:')
	call v%push('        case SY_F64:')
	call v%push('            n = (size_t)(a->elem == SY_F32 ? sy_fmt_f32(((float *)a->data)[i], tmp)')
	call v%push('                : sy_fmt_f64(((double *)a->data)[i], tmp));')
	call v%push('            while (n > 0 && tmp[n - 1] == '' '') n--;')
	call v%push('            while (n > 0 && *p == '' '') {')
	call v%push('                p++;')
	call v%push('                n--;')
	call v%push('            }')
	call v%push('            break;')
	call v%push('        case SY_BOOL:')
	call v%push('            p = a->data[i] ? "true" : "false";')
	call v%push('            n = strlen(p);')
	call v%push('            break;')
	call v%push('        default:')
	call v%push('            p = ((sy_str **)a->data)[i]->data;')
	call v%push('            n = (size_t)((sy_str **)a->data)[i]->len;')
	call v%push('            break;')
	call v%push('        }')
	call v%push('        sy_buf_put(&b, p, n);')
	call v%push('        if (i >= a->len - 1) continue;')
	call v%push('        sy_buf_put(&b, ", ", 2);')
	call v%push('')
	call v%push('        prod = a->size[0];')
	call v%push('        for (j = 1; j < a->rank; j++) {')
	call v%push('            if ((i + 1) % prod == 0) sy_buf_put(&b, "\n", 1);')
	call v%push('            prod *= a->size[j];')
	call v%push('        }')
	call v%push('    }')
	call v%push('')
	call v%push('    if (a != NULL && a->rank > 1) sy_buf_put(&b, "\n", 1);')
	call v%push('    sy_buf_put(&b, "]", 1);')
	call v%push('')
	call v%push('    s = sy_str_from(b.p, (int64_t)b.n);')
	call v%push('    free(b.p);')
	call v%push('    return s;')
	call v%push('}')
	call v%push('')
	call v%push('/*============================================================================*/')

end function native_rt_src

