	call v%push('void sy_oob(int64_t sub, int32_t dim, int32_t rank, int64_t size)')
	call v%push('{')
	call v%push('    if (rank == 0)')
	call v%push('        sy_rt_error("R33", "string index %lld is out of bounds for length %lld", (long long)sub,')
	call v%push('            (long long)size);')
	call v%push('    else if (rank == 1)')
	call v%push('        sy_rt_error("R33", "subscript %lld is out of bounds for size %lld", (long long)sub,')
	call v%push('            (long long)size);')
	call v%push('    else')
	call v%push('        sy_rt_error("R33", "subscript %lld is out of bounds for dimension %d of %d (size %lld)",')
	call v%push('            (long long)sub, (int)dim, (int)rank, (long long)size);')
	call v%push('}')
	call v%push('')
	call v%push('static int64_t *sy_sub_idx_raw(const sy_sub *s, int64_t n, int64_t *count)')
	call v%push('{')
	call v%push('    int64_t lo, hi, st, i, cnt;')
	call v%push('    int64_t *idx;')
	call v%push('')
	call v%push('    switch (s->kind) {')
	call v%push('    case SUB_SCALAR:')
	call v%push('        idx = (int64_t *)malloc(sizeof(int64_t));')
	call v%push('        idx[0] = s->lo;')
	call v%push('        *count = 1;')
	call v%push('        return idx;')
	call v%push('')
	call v%push('    case SUB_RANGE:')
	call v%push('    case SUB_ALL:')
	call v%push('        lo = (s->kind == SUB_ALL || (s->omit & 1)) ? 0 : s->lo;')
	call v%push('        hi = (s->kind == SUB_ALL || (s->omit & 2)) ? n : s->hi;')
	call v%push('        cnt = hi > lo ? hi - lo : 0;')
	call v%push('        idx = (int64_t *)malloc((size_t)(cnt > 0 ? cnt : 1) * sizeof(int64_t));')
	call v%push('        for (i = 0; i < cnt; i++) idx[i] = lo + i;')
	call v%push('        *count = cnt;')
	call v%push('        return idx;')
	call v%push('')
	call v%push('    case SUB_STEP:')
	call v%push('        st = s->st;')
	call v%push('        if (st == 0) sy_rt_error("R27", "subscript step is 0");')
	call v%push('        lo = (s->omit & 1) ? (st < 0 ? n - 1 : 0) : s->lo;')
	call v%push('        hi = (s->omit & 2) ? (st < 0 ? -1 : n) : s->hi;')
	call v%push('        cnt = sy_step_len(lo, st, hi);')
	call v%push('        sy_arr_len_check(1, &cnt);')
	call v%push('        idx = (int64_t *)malloc((size_t)(cnt > 0 ? cnt : 1) * sizeof(int64_t));')
	call v%push('        for (i = 0; i < cnt; i++) idx[i] = (int64_t)((uint64_t)lo + (uint64_t)i * (uint64_t)st);')
	call v%push('        *count = cnt;')
	call v%push('        return idx;')
	call v%push('')
	call v%push('    default:')
	call v%push('        cnt = s->vec != NULL ? s->vec->len : 0;')
	call v%push('        idx = (int64_t *)malloc((size_t)(cnt > 0 ? cnt : 1) * sizeof(int64_t));')
	call v%push('        for (i = 0; i < cnt; i++) {')
	call v%push('            idx[i] = s->vec->elem == SY_I64 ? ((int64_t *)s->vec->data)[i]')
	call v%push('                : (int64_t)((int32_t *)s->vec->data)[i];')
	call v%push('        }')
	call v%push('        *count = cnt;')
	call v%push('        return idx;')
	call v%push('    }')
	call v%push('}')
	call v%push('')
	call v%push('/* The indices that a subscript of dimension `dim` selects, of an array of `rank`, or')
	call v%push(' * of a string if rank is 0.  `n` is the extent */')
	call v%push('static int64_t *sy_sub_idx(const sy_sub *s, int64_t n, int64_t *count, int32_t dim, int32_t rank)')
	call v%push('{')
	call v%push('    int64_t *idx = sy_sub_idx_raw(s, n, count), i;')
	call v%push('')
	call v%push('    /* A range has a constant stride, so its first and last index are enough.  Those of')
	call v%push('     * a vector are each checked */')
	call v%push('    if (sy_bounds && *count > 0) {')
	call v%push('        if (s->kind == SUB_SCALAR || s->kind == SUB_RANGE || s->kind == SUB_ALL')
	call v%push('                || s->kind == SUB_STEP) {')
	call v%push('            if (idx[0] < 0 || idx[0] >= n) sy_oob(idx[0], dim, rank, n);')
	call v%push('            i = *count - 1;')
	call v%push('            if (idx[i] < 0 || idx[i] >= n) sy_oob(idx[i], dim, rank, n);')
	call v%push('        } else {')
	call v%push('            for (i = 0; i < *count; i++) {')
	call v%push('                if (idx[i] < 0 || idx[i] >= n) sy_oob(idx[i], dim, rank, n);')
	call v%push('            }')
	call v%push('        }')
	call v%push('    }')
	call v%push('    return idx;')
	call v%push('}')
	call v%push('')
	call v%push('/* Walks the elements that a subscript of each dimension of an array selects, in')
	call v%push(' * column-major order.  A scalar, a range, or `:` selects consecutive indices, which are')
	call v%push(' * not listed, only `lo[k]` and the count.  A stepped or vector subscript has a list in')
	call v%push(' * `idx[k]`.  `mul[k]` is the distance in elements between neighbors along dimension k */')
	call v%push('typedef struct {')
	call v%push('    int32_t rank;')
	call v%push('    int64_t *idx[SY_MAX_RANK];')
	call v%push('    int64_t lo[SY_MAX_RANK];')
	call v%push('    int64_t cnt[SY_MAX_RANK], pos[SY_MAX_RANK], ext[SY_MAX_RANK], mul[SY_MAX_RANK];')
	call v%push('    int64_t total;')
	call v%push('} sy_walk;')
	call v%push('')
	call v%push('static void sy_walk_init(sy_walk *w, const sy_arr *a, const sy_sub *subs)')
	call v%push('{')
	call v%push('    int32_t k;')
	call v%push('    int64_t mult = 1;')
	call v%push('')
	call v%push('    if (a->rank > SY_MAX_RANK) sy_fatal("array rank is too big");')
	call v%push('    w->rank = a->rank;')
	call v%push('    w->total = 1;')
	call v%push('    for (k = 0; k < a->rank; k++) {')
	call v%push('        const sy_sub *s = &subs[k];')
	call v%push('        int64_t n = a->size[k], hi;')
	call v%push('')
	call v%push('        if (s->kind == SUB_SCALAR || s->kind == SUB_RANGE || s->kind == SUB_ALL) {')
	call v%push('            /* The same as sy_sub_idx_raw() and sy_sub_idx(), without the list */')
	call v%push('            if (s->kind == SUB_SCALAR) {')
	call v%push('                w->lo[k] = s->lo;')
	call v%push('                w->cnt[k] = 1;')
	call v%push('            } else {')
	call v%push('                w->lo[k] = (s->kind == SUB_ALL || (s->omit & 1)) ? 0 : s->lo;')
	call v%push('                hi = (s->kind == SUB_ALL || (s->omit & 2)) ? n : s->hi;')
	call v%push('                w->cnt[k] = hi > w->lo[k] ? hi - w->lo[k] : 0;')
	call v%push('            }')
	call v%push('            w->idx[k] = NULL;')
	call v%push('            if (sy_bounds && w->cnt[k] > 0) {')
	call v%push('                int64_t last = w->lo[k] + w->cnt[k] - 1;')
	call v%push('')
	call v%push('                if (w->lo[k] < 0 || w->lo[k] >= n) sy_oob(w->lo[k], k + 1, a->rank, n);')
	call v%push('                if (last < 0 || last >= n) sy_oob(last, k + 1, a->rank, n);')
	call v%push('            }')
	call v%push('        } else {')
	call v%push('            w->idx[k] = sy_sub_idx(s, n, &w->cnt[k], k + 1, a->rank);')
	call v%push('            w->lo[k] = 0;')
	call v%push('        }')
	call v%push('        w->ext[k] = n;')
	call v%push('        w->mul[k] = mult;')
	call v%push('        mult *= n;')
	call v%push('        w->pos[k] = 0;')
	call v%push('        w->total *= w->cnt[k];')
	call v%push('    }')
	call v%push('}')
	call v%push('')
	call v%push('/* The index along dimension k of its p-th selected element */')
	call v%push('static inline int64_t sy_walk_at(const sy_walk *w, int32_t k, int64_t p)')
	call v%push('{')
	call v%push('    return w->idx[k] != NULL ? w->idx[k][p] : w->lo[k] + p;')
	call v%push('}')
	call v%push('')
	call v%push('static int64_t sy_walk_next(sy_walk *w)')
	call v%push('{')
	call v%push('    int32_t k;')
	call v%push('    int64_t lin = 0;')
	call v%push('')
	call v%push('    for (k = 0; k < w->rank; k++) lin += sy_walk_at(w, k, w->pos[k]) * w->mul[k];')
	call v%push('    for (k = 0; k < w->rank; k++) {')
	call v%push('        if (++w->pos[k] < w->cnt[k]) break;')
	call v%push('        w->pos[k] = 0;')
	call v%push('    }')
	call v%push('    return lin;')
	call v%push('}')
	call v%push('')
	call v%push('static void sy_walk_free(sy_walk *w)')
	call v%push('{')
	call v%push('    int32_t k;')
	call v%push('')
	call v%push('    for (k = 0; k < w->rank; k++) free(w->idx[k]);')
	call v%push('}')
	call v%push('')
	call v%push('/* Do the selected elements come in runs of consecutive ones in storage?  If so, `*run`')
	call v%push(' * is the length of each, and `*d` is the first dimension that is not part of one, so')
	call v%push(' * dimensions 0 to d - 1 are walked all at once.  Dimension 0 has to be consecutive,')
	call v%push(' * and so does each one that is merged into the run, which needs all of the dimensions')
	call v%push(' * before it to be whole.  So `a[:, 1:3]` is a single run, and `a[1:3, :]` is not */')
	call v%push('static int sy_walk_runs(const sy_walk *w, int64_t *run, int32_t *d)')
	call v%push('{')
	call v%push('    if (w->total <= 0 || w->rank == 0 || w->idx[0] != NULL) return 0;')
	call v%push('    *run = w->cnt[0];')
	call v%push('    *d = 1;')
	call v%push('    while (*d < w->rank && w->idx[*d] == NULL')
	call v%push('            && w->lo[*d - 1] == 0 && w->cnt[*d - 1] == w->ext[*d - 1]) {')
	call v%push('        *run *= w->cnt[*d];')
	call v%push('        ++*d;')
	call v%push('    }')
	call v%push('    return 1;')
	call v%push('}')
	call v%push('')
	call v%push('/* Where the next run starts, then step the outer dimensions (from d) on to the one after */')
	call v%push('static int64_t sy_walk_run_next(sy_walk *w, int32_t d)')
	call v%push('{')
	call v%push('    int32_t k;')
	call v%push('    int64_t lin = 0;')
	call v%push('')
	call v%push('    for (k = 0; k < d; k++) lin += w->lo[k] * w->mul[k];')
	call v%push('    for (k = d; k < w->rank; k++) lin += sy_walk_at(w, k, w->pos[k]) * w->mul[k];')
	call v%push('    for (k = d; k < w->rank; k++) {')
	call v%push('        if (++w->pos[k] < w->cnt[k]) break;')
	call v%push('        w->pos[k] = 0;')
	call v%push('    }')
	call v%push('    return lin;')
	call v%push('}')
	call v%push('')
	call v%push('/* a[subs], where at least one subscript is not a single element.  The')
	call v%push(' * dimensions of single elements are dropped from the shape of the result */')
	call v%push('sy_arr *sy_arr_slice(const sy_arr *a, const sy_sub *subs)')
	call v%push('{')
	call v%push('    sy_walk w;')
	call v%push('    int64_t sizes[SY_MAX_RANK], t, lin, run;')
	call v%push('    int32_t k, d, rr = 0;')
	call v%push('    size_t es = sy_esize(a->elem);')
	call v%push('    sy_arr *out;')
	call v%push('')
	call v%push('    sy_walk_init(&w, a, subs);')
	call v%push('    for (k = 0; k < a->rank; k++) {')
	call v%push('        if (subs[k].kind != SUB_SCALAR) sizes[rr++] = w.cnt[k];')
	call v%push('    }')
	call v%push('    out = sy_arr_alloc(a->elem, rr, sizes, 0);')
	call v%push('')
	call v%push('    if (!sy_eptr(a->elem) && sy_walk_runs(&w, &run, &d)) {')
	call v%push('        for (t = 0; t < w.total; t += run) {')
	call v%push('            lin = sy_walk_run_next(&w, d);')
	call v%push('            memcpy(out->data + (size_t)t * es, a->data + (size_t)lin * es, (size_t)run * es);')
	call v%push('        }')
	call v%push('        sy_walk_free(&w);')
	call v%push('        return out;')
	call v%push('    }')
	call v%push('')
	call v%push('    for (t = 0; t < out->len; t++) {')
	call v%push('        lin = sy_walk_next(&w);')
	call v%push('        if (sy_eptr(a->elem)) {')
	call v%push('            sy_eptr_free(a->elem, ((void **)out->data)[t]);')
	call v%push('            ((void **)out->data)[t] = sy_eptr_dup(a->elem, ((void **)a->data)[lin]);')
	call v%push('        } else {')
	call v%push('            memcpy(out->data + (size_t)t * es, a->data + (size_t)lin * es, es);')
	call v%push('        }')
	call v%push('    }')
	call v%push('    sy_walk_free(&w);')
	call v%push('    return out;')
	call v%push('}')
	call v%push('')
	call v%push('/* The elements of a[subs] in place, where `a` has rank 1 and the one subscript is a range or')
