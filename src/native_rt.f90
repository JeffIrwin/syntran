	call v%push('    }')
	call v%push('    if (!f->wr) {')
	call v%push('        sy_rt_error("R13", "%s() was called for file \"%s\" which was not opened in write "')
	call v%push('            "mode \"w\"", fn, f->name->data);')
	call v%push('    }')
	call v%push('    if (is_writeln && f->bin) {')
	call v%push('        sy_rt_error("R43", "writeln() was called for file \"%s\" which was opened in binary "')
	call v%push('            "mode \"b\".  Use write() instead", f->name->data);')
	call v%push('    }')
	call v%push('}')
	call v%push('')
	call v%push('static void sy_file_put(sy_file *f, const void *p, size_t n)')
	call v%push('{')
	call v%push('    if (n > 0 && fwrite(p, 1, n, f->u->fp) != n) {')
	call v%push('        sy_rt_error("R30", "cannot write() to file \"%s\" (iostat = %d)", f->name->data, errno);')
	call v%push('    }')
	call v%push('}')
	call v%push('')
	call v%push('static void sy_file_put_str(sy_file *f, sy_str *s)')
	call v%push('{')
	call v%push('    sy_file_put(f, s->data, (size_t)s->len);')
	call v%push('    sy_str_free(s);')
	call v%push('}')
	call v%push('')
	call v%push('static void sy_file_bad_type(const sy_file *f, const char *tname)')
	call v%push('{')
	call v%push('    sy_rt_error("R45", "write() can not write a value of type `%s` to file \"%s\" which "')
	call v%push('        "was opened in binary mode \"b\"", tname, f->name->data);')
	call v%push('}')
	call v%push('')
	call v%push('void sy_file_wnl(sy_file *f)')
	call v%push('{')
	call v%push('    sy_file_put(f, "\n", 1);')
	call v%push('}')
	call v%push('')
	call v%push('void sy_file_wstr(sy_file *f, const sy_str *s)')
	call v%push('{')
	call v%push('    sy_file_put(f, s->data, (size_t)s->len);')
	call v%push('}')
	call v%push('')
	call v%push('void sy_file_wi32(sy_file *f, int32_t x)')
	call v%push('{')
	call v%push('    if (f->bin) sy_file_put(f, &x, sizeof x);')
	call v%push('    else sy_file_put_str(f, sy_str_i32(x));')
	call v%push('}')
	call v%push('')
	call v%push('void sy_file_wi64(sy_file *f, int64_t x)')
	call v%push('{')
	call v%push('    if (f->bin) sy_file_put(f, &x, sizeof x);')
	call v%push('    else sy_file_put_str(f, sy_str_i64(x));')
	call v%push('}')
	call v%push('')
	call v%push('void sy_file_wf32(sy_file *f, float x)')
	call v%push('{')
	call v%push('    if (f->bin) sy_file_put(f, &x, sizeof x);')
	call v%push('    else sy_file_put_str(f, sy_str_f32(x));')
	call v%push('}')
	call v%push('')
	call v%push('void sy_file_wf64(sy_file *f, double x)')
	call v%push('{')
	call v%push('    if (f->bin) sy_file_put(f, &x, sizeof x);')
	call v%push('    else sy_file_put_str(f, sy_str_f64(x));')
	call v%push('}')
	call v%push('')
	call v%push('void sy_file_wbool(sy_file *f, int8_t x)')
	call v%push('{')
	call v%push('    if (f->bin) sy_file_put(f, &x, sizeof x);')
	call v%push('    else sy_file_put_str(f, sy_str_bool(x));')
	call v%push('}')
	call v%push('')
	call v%push('/* An array, whose elements are enums if `names` is not NULL */')
	call v%push('void sy_file_warr(sy_file *f, const sy_arr *a, const sy_str *const *names, const char *tname)')
	call v%push('{')
	call v%push('    if (!f->bin) {')
	call v%push('        sy_file_put_str(f, names != NULL ? sy_arr_str_names(a, names) : sy_arr_str(a));')
	call v%push('        return;')
	call v%push('    }')
	call v%push('    if (names != NULL || a->elem == SY_STR || a->elem == SY_ARR || a->elem == SY_STRUCT) {')
	call v%push('        sy_file_bad_type(f, tname);')
	call v%push('    }')
	call v%push('    sy_file_put(f, a->data, (size_t)a->len * sy_esize(a->elem));')
	call v%push('}')
	call v%push('')
	call v%push('void sy_file_wstruct(sy_file *f, const sy_struct *s, const char *tname)')
	call v%push('{')
	call v%push('    if (f->bin) sy_file_bad_type(f, tname);')
	call v%push('    sy_file_put_str(f, sy_struct_str(s));')
	call v%push('}')
	call v%push('')
	call v%push('void sy_file_wenum(sy_file *f, int32_t v, const sy_str *const *names, const char *tname)')
	call v%push('{')
	call v%push('    if (f->bin) sy_file_bad_type(f, tname);')
	call v%push('    sy_file_put(f, names[v]->data, (size_t)names[v]->len);')
	call v%push('}')
	call v%push('')
	call v%push('/*----------------------------------------------------------------------------*/')
	call v%push('')
	call v%push('/* std::read_<type>().  In a text file, values are separated by blanks, tabs, or')
	call v%push(' * commas and can be on different lines.  The rest of the line of the last value')
	call v%push(' * is skipped.  Unlike a list-directed read, `/`, `*`, and quotes are not special')
	call v%push(' * and an empty field like the one in `1,,3` is not a null value: they are all')
	call v%push(' * errors, so that a bad value is never skipped or repeated.  A binary file is')
	call v%push(' * read as the bytes the values are stored as.  The values go to `out`, which has')
	call v%push(' * room for `n` of the type `elem` */')
	call v%push('static void sy_read_fail(const sy_file *f, const char *fn, const char *what)')
	call v%push('{')
	call v%push('    sy_rt_error("R44", "cannot %s() from file \"%s\" %s", fn, f->name->data, what);')
	call v%push('}')
	call v%push('')
	call v%push('static void sy_read_bad(const sy_file *f, const char *fn, const char *tok)')
	call v%push('{')
	call v%push('    char what[256];')
	call v%push('')
	call v%push('    if (tok[0] == ''\0'') snprintf(what, sizeof what, "(empty value)");')
	call v%push('    else snprintf(what, sizeof what, "(invalid value \"%.200s\")", tok);')
	call v%push('    sy_read_fail(f, fn, what);')
	call v%push('}')
	call v%push('')
	call v%push('static int sy_is_sep(int c)')
	call v%push('{')
	call v%push('    return c == '' '' || c == ''\t'' || c == ''\r'' || c == '','';')
	call v%push('}')
	call v%push('')
	call v%push('/* Fortran''s list-directed read takes a `d` for an exponent too */')
	call v%push('static int sy_tok_value(int32_t elem, const char *tok, void *out)')
	call v%push('{')
	call v%push('    char *end, tmp[128];')
	call v%push('    size_t i, n = strlen(tok);')
	call v%push('    long long iv;')
	call v%push('    double dv;')
	call v%push('')
	call v%push('    if (n == 0 || n >= sizeof tmp) return 0;')
	call v%push('    errno = 0;')
	call v%push('    if (elem == SY_I32 || elem == SY_I64) {')
	call v%push('        iv = strtoll(tok, &end, 10);')
	call v%push('        if (*end != ''\0'' || errno != 0) return 0;')
	call v%push('        if (elem == SY_I32) {')
	call v%push('            if (iv < -2147483648LL || iv > 2147483647LL) return 0;')
	call v%push('            *(int32_t *)out = (int32_t)iv;')
	call v%push('        } else {')
	call v%push('            *(int64_t *)out = (int64_t)iv;')
	call v%push('        }')
	call v%push('        return 1;')
	call v%push('    }')
	call v%push('    for (i = 0; i <= n; i++) tmp[i] = (tok[i] == ''d'' || tok[i] == ''D'') ? ''e'' : tok[i];')
	call v%push('    dv = strtod(tmp, &end);')
	call v%push('    if (*end != ''\0'' || end == tmp) return 0;')
	call v%push('    if (elem == SY_F32) *(float *)out = (float)dv;')
	call v%push('    else *(double *)out = dv;')
	call v%push('    return 1;')
	call v%push('}')
	call v%push('')
	call v%push('static void sy_read_values(sy_file *f, int32_t elem, int64_t n, void *out)')
	call v%push('{')
	call v%push('    static const char *const fns[] = {"read_i32", "read_i64", "read_f32", "read_f64"};')
	call v%push('    const char *fn = fns[elem];')
	call v%push('    size_t es = sy_esize(elem);')
	call v%push('    int64_t k = 0, i, j;')
	call v%push('    int hit, after_tok = 0;')
	call v%push('    char tok[256];')
	call v%push('    sy_str *line;')
	call v%push('')
	call v%push('    sy_file_rcheck(f, fn, "R9", "R10", NULL);')
	call v%push('    if (sy_file_at_eof(f)) sy_read_fail(f, fn, "past the end of the file");')
	call v%push('')
	call v%push('    if (f->bin) {')
	call v%push('        if (n > 0 && fread(out, es, (size_t)n, f->u->fp) != (size_t)n) {')
	call v%push('            sy_read_fail(f, fn, "past the end of the file");')
	call v%push('        }')
	call v%push('        return;')
	call v%push('    }')
	call v%push('')
	call v%push('    while (k < n) {')
	call v%push('        line = sy_read_line(f->u->fp, &hit);')
	call v%push('        if (hit && line->len == 0) sy_read_fail(f, fn, "past the end of the file");')
	call v%push('        i = 0;')
	call v%push('        while (i < line->len && k < n) {')
	call v%push('            char c = line->data[i];')
	call v%push('')
	call v%push('            if (c == '' '' || c == ''\t'' || c == ''\r'') {')
	call v%push('                i++;')
	call v%push('            } else if (c == '','') {')
	call v%push('                if (!after_tok) sy_read_bad(f, fn, "");')
	call v%push('                after_tok = 0;')
	call v%push('                i++;')
	call v%push('            } else {')
	call v%push('                for (j = i; j < line->len && !sy_is_sep(line->data[j]); j++) {}')
	call v%push('                if (j - i >= (int64_t)sizeof tok) sy_read_bad(f, fn, "");')
	call v%push('                memcpy(tok, line->data + i, (size_t)(j - i));')
	call v%push('                tok[j - i] = ''\0'';')
	call v%push('                if (strpbrk(tok, "/*''\"") != NULL ||')
	call v%push('                    !sy_tok_value(elem, tok, (char *)out + (size_t)k * es)) {')
	call v%push('                    sy_read_bad(f, fn, tok);')
	call v%push('                }')
	call v%push('                k++;')
	call v%push('                after_tok = 1;')
	call v%push('                i = j;')
	call v%push('            }')
	call v%push('        }')
	call v%push('        sy_str_free(line);')
	call v%push('    }')
	call v%push('}')
	call v%push('')
	call v%push('int32_t sy_file_read_i32(sy_file *f)')
	call v%push('{')
	call v%push('    int32_t x = 0;')
	call v%push('')
	call v%push('    sy_read_values(f, SY_I32, 1, &x);')
	call v%push('    return x;')
	call v%push('}')
	call v%push('')
	call v%push('int64_t sy_file_read_i64(sy_file *f)')
	call v%push('{')
	call v%push('    int64_t x = 0;')
	call v%push('')
	call v%push('    sy_read_values(f, SY_I64, 1, &x);')
	call v%push('    return x;')
	call v%push('}')
	call v%push('')
	call v%push('float sy_file_read_f32(sy_file *f)')
	call v%push('{')
	call v%push('    float x = 0;')
	call v%push('')
	call v%push('    sy_read_values(f, SY_F32, 1, &x);')
	call v%push('    return x;')
	call v%push('}')
	call v%push('')
	call v%push('double sy_file_read_f64(sy_file *f)')
	call v%push('{')
	call v%push('    double x = 0;')
	call v%push('')
	call v%push('    sy_read_values(f, SY_F64, 1, &x);')
	call v%push('    return x;')
	call v%push('}')
	call v%push('')
	call v%push('/* A rank 1 array of n values.  The type of the elements is SY_I32, etc. */')
	call v%push('sy_arr *sy_file_read_arr(sy_file *f, int32_t elem, int64_t n)')
	call v%push('{')
	call v%push('    sy_arr *a;')
	call v%push('')
	call v%push('    if (n < 0) {')
	call v%push('        sy_rt_error("R44", "cannot read_%s() a negative number of values (n = %lld)",')
	call v%push('            elem == SY_I32 ? "i32" : elem == SY_I64 ? "i64" : elem == SY_F32 ? "f32" : "f64",')
	call v%push('            (long long)n);')
	call v%push('    }')
	call v%push('    a = sy_arr_new(elem, 1, &n);')
	call v%push('    sy_read_values(f, elem, n, a->data);')
	call v%push('    return a;')
	call v%push('}')

end function native_rt_src

