	call v%push('                                                                                          \')
	call v%push('    /* Solve with the n x n factors and 1-based pivots of the above.  b is n x nrhs */    \')
	call v%push('    static void sy_lu_subst_##S(int n, int nrhs, const T *a, const int *ipiv, T *b)       \')
	call v%push('    {                                                                                     \')
	call v%push('        int i, j, k, p;                                                                   \')
	call v%push('        T tmp, bj;                                                                        \')
	call v%push('        for (i = 0; i < n; i++) {                                                         \')
	call v%push('            p = ipiv[i] - 1;                                                              \')
	call v%push('            if (p == i) continue;                                                         \')
	call v%push('            for (k = 0; k < nrhs; k++) {                                                  \')
	call v%push('                tmp = b[i + (size_t)k * n];                                               \')
	call v%push('                b[i + (size_t)k * n] = b[p + (size_t)k * n];                              \')
	call v%push('                b[p + (size_t)k * n] = tmp;                                               \')
	call v%push('            }                                                                             \')
	call v%push('        }                                                                                 \')
	call v%push('        for (k = 0; k < nrhs; k++) {                                                      \')
	call v%push('            T *bk = b + (size_t)k * n;                                                    \')
	call v%push('            for (j = 0; j < n - 1; j++) {                                                 \')
	call v%push('                bj = bk[j];                                                               \')
	call v%push('                for (i = j + 1; i < n; i++) bk[i] -= bj * a[i + (size_t)j * n];           \')
	call v%push('            }                                                                             \')
	call v%push('            for (j = n - 1; j >= 0; j--) {                                                \')
	call v%push('                bk[j] /= a[j + (size_t)j * n];                                            \')
	call v%push('                bj = bk[j];                                                               \')
	call v%push('                for (i = 0; i < j; i++) bk[i] -= bj * a[i + (size_t)j * n];               \')
	call v%push('            }                                                                             \')
	call v%push('        }                                                                                 \')
	call v%push('    }')
	call v%push('')
	call v%push('SY_LU(float, f32, fabsf)')
	call v%push('SY_LU(double, f64, fabs)')
	call v%push('')
	call v%push('/* getrf, getrs, and gesv for either type, through LAPACK if there is one */')
	call v%push('#ifdef SY_BLAS')
	call v%push('#define SY_LAPACK(T, S, GETRF, GETRS, GESV)                                               \')
	call v%push('    static int sy_getrf_##S(int m, int n, T *a, int *ipiv)                                \')
	call v%push('    {                                                                                     \')
	call v%push('        int info = 0;                                                                     \')
	call v%push('        if (m > 0 && n > 0) GETRF(&m, &n, a, &m, ipiv, &info);                            \')
	call v%push('        return info;                                                                      \')
	call v%push('    }                                                                                     \')
	call v%push('    static void sy_getrs_##S(int n, int nrhs, const T *a, const int *ipiv, T *b)          \')
	call v%push('    {                                                                                     \')
	call v%push('        int info = 0;                                                                     \')
	call v%push('        if (n > 0 && nrhs > 0) GETRS("N", &n, &nrhs, a, &n, ipiv, b, &n, &info);          \')
	call v%push('    }                                                                                     \')
	call v%push('    static int sy_gesv_##S(int n, int nrhs, T *w, int *ipiv, T *b)                        \')
	call v%push('    {                                                                                     \')
	call v%push('        int info = 0;                                                                     \')
	call v%push('        if (n > 0 && nrhs > 0) GESV(&n, &nrhs, w, &n, ipiv, b, &n, &info);                \')
	call v%push('        return info;                                                                      \')
	call v%push('    }')
	call v%push('SY_LAPACK(float, f32, sgetrf_, sgetrs_, sgesv_)')
	call v%push('SY_LAPACK(double, f64, dgetrf_, dgetrs_, dgesv_)')
	call v%push('#else')
	call v%push('#define SY_LAPACK(T, S)                                                                   \')
	call v%push('    static int sy_getrf_##S(int m, int n, T *a, int *ipiv)                                \')
	call v%push('    {                                                                                     \')
	call v%push('        return m > 0 && n > 0 ? sy_lu_factor_##S(m, n, a, ipiv) : 0;                      \')
	call v%push('    }                                                                                     \')
	call v%push('    static void sy_getrs_##S(int n, int nrhs, const T *a, const int *ipiv, T *b)          \')
	call v%push('    {                                                                                     \')
	call v%push('        if (n > 0 && nrhs > 0) sy_lu_subst_##S(n, nrhs, a, ipiv, b);                      \')
	call v%push('    }                                                                                     \')
	call v%push('    static int sy_gesv_##S(int n, int nrhs, T *w, int *ipiv, T *b)                        \')
	call v%push('    {                                                                                     \')
	call v%push('        int info;                                                                         \')
	call v%push('        if (n <= 0 || nrhs <= 0) return 0;                                                \')
	call v%push('        info = sy_lu_factor_##S(n, n, w, ipiv);                                           \')
	call v%push('        if (info == 0) sy_lu_subst_##S(n, nrhs, w, ipiv, b);                              \')
	call v%push('        return info;                                                                      \')
	call v%push('    }')
	call v%push('SY_LAPACK(float, f32)')
	call v%push('SY_LAPACK(double, f64)')
	call v%push('#endif')
	call v%push('')
	call v%push('static void sy_singular(const char *fn, int info)')
	call v%push('{')
	call v%push('    sy_rt_error("R41", "matrix `A` in %s() is singular: pivot U[%d, %d] is zero", fn,')
	call v%push('        info - 1, info - 1);')
	call v%push('}')
	call v%push('')
	call v%push('/* solve(a, b): the x of a x = b, where b is a vector or a matrix.  Neither is')
	call v%push(' * changed */')
	call v%push('sy_arr *sy_solve(const sy_arr *a, const sy_arr *b)')
	call v%push('{')
	call v%push('    int n, nrhs = 1, info, *ipiv;')
	call v%push('    sy_arr *x, *w;')
	call v%push('')
	call v%push('    if (a->size[0] != a->size[1] || a->size[0] != b->size[0]) {')
	call v%push('        if (a->size[0] != a->size[1]) {')
	call v%push('            sy_rt_error("R40", "matrix `A` in solve() is not square: %lld x %lld",')
	call v%push('                (long long)a->size[0], (long long)a->size[1]);')
	call v%push('        }')
	call v%push('        sy_rt_error("R40", "size mismatch in solve(): `A` is %lld x %lld but `b` has %lld rows",')
	call v%push('            (long long)a->size[0], (long long)a->size[1], (long long)b->size[0]);')
	call v%push('    }')
	call v%push('    n = (int)a->size[0];')
	call v%push('    if (b->rank == 2) nrhs = (int)b->size[1];')
	call v%push('')
	call v%push('    x = sy_arr_dup(b);')
	call v%push('    w = sy_arr_dup(a);')
	call v%push('    ipiv = (int *)malloc(sizeof(int) * (size_t)(n > 0 ? n : 1));')
	call v%push('    if (ipiv == NULL) sy_fatal("out of memory");')
	call v%push('')
	call v%push('    if (a->elem == SY_F32) {')
	call v%push('        info = sy_gesv_f32(n, nrhs, (float *)w->data, ipiv, (float *)x->data);')
	call v%push('    } else {')
	call v%push('        info = sy_gesv_f64(n, nrhs, (double *)w->data, ipiv, (double *)x->data);')
	call v%push('    }')
	call v%push('    free(ipiv);')
	call v%push('    sy_arr_free(w);')
	call v%push('    if (info > 0) {')
	call v%push('        sy_arr_free(x);')
	call v%push('        sy_singular("solve", info);')
	call v%push('    }')
	call v%push('    return x;')
	call v%push('}')
	call v%push('')
	call v%push('/* lu_factor(&a, &info): `a` becomes its L and U factors.  The result is the')
	call v%push(' * 0-based pivots.  If `info` is NULL, a zero pivot is an error, and otherwise it')
	call v%push(' * is what `info` gets */')
	call v%push('sy_arr *sy_lu_factor(sy_arr *a, int32_t *info_out)')
	call v%push('{')
	call v%push('    int m = (int)a->size[0], n = (int)a->size[1], i, info;')
	call v%push('    int64_t np = m < n ? m : n;')
	call v%push('    sy_arr *piv = sy_arr_new1(SY_I32, np);')
	call v%push('')
	call v%push('    info = a->elem == SY_F32 ? sy_getrf_f32(m, n, (float *)a->data, (int *)piv->data)')
	call v%push('                             : sy_getrf_f64(m, n, (double *)a->data, (int *)piv->data);')
	call v%push('    for (i = 0; i < np; i++) ((int32_t *)piv->data)[i] -= 1;')
	call v%push('')
	call v%push('    if (info_out != NULL) {')
	call v%push('        *info_out = info;')
	call v%push('    } else if (info > 0) {')
	call v%push('        sy_arr_free(piv);')
	call v%push('        sy_singular("lu_factor", info);')
	call v%push('    }')
	call v%push('    return piv;')
	call v%push('}')
	call v%push('')
	call v%push('/* lu_solve(a, ipiv, &b): the factors and pivots of lu_factor(), and b becomes x */')
	call v%push('void sy_lu_solve(const sy_arr *a, const sy_arr *ipiv, sy_arr *b)')
	call v%push('{')
	call v%push('    int m = (int)a->size[0], n = (int)a->size[1], nrhs = 1, i, *ip1;')
	call v%push('    const int32_t *p = (const int32_t *)ipiv->data;')
	call v%push('')
	call v%push('    if (m != n || m != b->size[0]) {')
	call v%push('        if (m != n) {')
	call v%push('            sy_rt_error("R40", "matrix `A` in lu_solve() is not square: %d x %d", m, n);')
	call v%push('        }')
	call v%push('        sy_rt_error("R40", "size mismatch in lu_solve(): `A` is %d x %d but `b` has %lld rows",')
	call v%push('            m, n, (long long)b->size[0]);')
	call v%push('    }')
	call v%push('    if (ipiv->len != n) {')
	call v%push('        sy_rt_error("R42", "size mismatch in lu_solve(): `A` is %d x %d but `ipiv` has %lld "')
	call v%push('            "elements", n, n, (long long)ipiv->len);')
	call v%push('    }')
	call v%push('    for (i = 0; i < n; i++) {')
	call v%push('        if (p[i] < 0 || p[i] >= n) {')
	call v%push('            sy_rt_error("R42", "invalid pivot in lu_solve(): ipiv[%d] is %d, which is outside "')
	call v%push('                "of [0, %d)", i, (int)p[i], n);')
	call v%push('        }')
	call v%push('    }')
	call v%push('    if (b->rank == 2) nrhs = (int)b->size[1];')
	call v%push('')
	call v%push('    /* An exactly zero diagonal of U means that the factors are of a singular matrix */')
	call v%push('    for (i = 0; i < n; i++) {')
	call v%push('        double d = a->elem == SY_F32 ? (double)((const float *)a->data)[i + (size_t)i * n]')
	call v%push('                                     : ((const double *)a->data)[i + (size_t)i * n];')
	call v%push('        if (d == 0) sy_singular("lu_solve", i + 1);')
	call v%push('    }')
	call v%push('')
	call v%push('    ip1 = (int *)malloc(sizeof(int) * (size_t)(n > 0 ? n : 1));')
	call v%push('    if (ip1 == NULL) sy_fatal("out of memory");')
	call v%push('    for (i = 0; i < n; i++) ip1[i] = p[i] + 1;')
	call v%push('    if (a->elem == SY_F32) {')
	call v%push('        sy_getrs_f32(n, nrhs, (const float *)a->data, ip1, (float *)b->data);')
	call v%push('    } else {')
	call v%push('        sy_getrs_f64(n, nrhs, (const double *)a->data, ip1, (double *)b->data);')
	call v%push('    }')
	call v%push('    free(ip1);')
	call v%push('}')
	call v%push('')
	call v%push('/*============================================================================*/')
	call v%push('')
	call v%push('/* sind(), cosd(), and tand(): trig fns of degrees.  The angles that have a')
	call v%push(' * simple result, like sind(30) and tand(45), have exactly that, which')
	call v%push(' * sin(x * pi / 180) would not.  Everything else is within an ulp or so of the')
	call v%push(' * interpreter''s, which is libgfortran''s.  An f32 is done as an f64 and rounded */')
	call v%push('')
	call v%push('#define SY_PI 3.14159265358979323846')
	call v%push('')
	call v%push('/* sin(a) of a degrees in [0, 90] */')
	call v%push('static double sy_sin_deg(double a)')
	call v%push('{')
	call v%push('    if (a == 0) return 0;')
	call v%push('    if (a == 30) return 0.5;')
	call v%push('    if (a == 90) return 1;')
	call v%push('    return sin(a * (SY_PI / 180));')
	call v%push('}')
	call v%push('')
	call v%push('/* tan(a) of a degrees in [0, 90) */')
	call v%push('static double sy_tan_deg(double a)')
	call v%push('{')
	call v%push('    if (a == 0) return 0;')
	call v%push('    if (a == 45) return 1;')
	call v%push('    return tan(a * (SY_PI / 180));')
	call v%push('}')
	call v%push('')
	call v%push('double sy_sind_f64(double x)')
	call v%push('{')
	call v%push('    double u, v;')
	call v%push('    int neg;')
	call v%push('')
	call v%push('    if (isnan(x) || isinf(x)) return NAN;')
	call v%push('    u = fmod(fabs(x), 360);')
	call v%push('    neg = u >= 180;')
	call v%push('    if (neg) u -= 180;')
	call v%push('    if (u > 90) u = 180 - u;')
	call v%push('    v = sy_sin_deg(u);')
	call v%push('    if (neg) v = -v;')
	call v%push('    return signbit(x) ? -v : v;')
	call v%push('}')
	call v%push('')
	call v%push('double sy_cosd_f64(double x)')
	call v%push('{')
	call v%push('    double u;')
	call v%push('    int neg;')
	call v%push('')
	call v%push('    if (isnan(x) || isinf(x)) return NAN;')
	call v%push('    u = fmod(fabs(x), 360);')
	call v%push('    if (u > 180) u = 360 - u;')
	call v%push('    neg = u > 90;')
	call v%push('    if (neg) u = 180 - u;')
	call v%push('    return neg ? -sy_sin_deg(90 - u) : sy_sin_deg(90 - u);')
	call v%push('}')
	call v%push('')
	call v%push('double sy_tand_f64(double x)')
	call v%push('{')
	call v%push('    double u, v, t;')
	call v%push('')
	call v%push('    if (isnan(x) || isinf(x)) return NAN;')
	call v%push('    u = fmod(fabs(x), 360);')
	call v%push('    if (u == 90) {')
	call v%push('        t = INFINITY;')
	call v%push('    } else if (u == 270) {')
	call v%push('        t = -INFINITY;')
	call v%push('    } else {')
	call v%push('        v = fmod(u, 180);')
	call v%push('        t = v < 90 ? sy_tan_deg(v) : -sy_tan_deg(180 - v);')
	call v%push('    }')
	call v%push('    return signbit(x) ? -t : t;')
	call v%push('}')
	call v%push('')
	call v%push('float sy_sind_f32(float x) { return (float)sy_sind_f64((double)x); }')
	call v%push('float sy_cosd_f32(float x) { return (float)sy_cosd_f64((double)x); }')
	call v%push('float sy_tand_f32(float x) { return (float)sy_tand_f64((double)x); }')
	call v%push('')
	call v%push('/*============================================================================*/')
	call v%push('')
	call v%push('#ifdef SYNTRAN_LLVM')
	call v%push('')
	call v%push('/* Run the main() of a program that was compiled in memory, as if it were a fresh')
	call v%push(' * process.  The state of the runtime is reset first.  The return value is 0 if the')
	call v%push(' * program ran to the end, 1 if it stopped with a runtime error, and 2 if it called')
	call v%push(' * std::exit() */')
	call v%push('int sy_jit_call(int (*fn)(int, char **))')
	call v%push('{')
	call v%push('    static char name[] = "syntran";')
	call v%push('    char *argv[2];')
	call v%push('')
	call v%push('    argv[0] = name;')
	call v%push('    argv[1] = NULL;')
	call v%push('')
	call v%push('    free(sy_jit_res);')
	call v%push('    free(sy_jit_msg);')
	call v%push('    sy_jit_res = NULL;')
	call v%push('    sy_jit_msg = NULL;')
	call v%push('    sy_jit_kind = 0;')
	call v%push('    sy_jit_code = 0;')
	call v%push('')
	call v%push('    sy_loc = 0;')
	call v%push('    sy_depth = 0;')
	call v%push('    sy_loc_tab = NULL;')
	call v%push('    sy_nloc = 0;')
	call v%push('    sy_fn_tab = NULL;')
	call v%push('    sy_nfn = 0;')
	call v%push('    sy_bounds = 0;')
	call v%push('    sy_stdin_eof = 0;')
	call v%push('    memset(sy_unit_used, 0, sizeof(sy_unit_used));')
	call v%push('')
	call v%push('    sy_jit = 1;')
	call v%push('    if (SY_SETJMP() == 0) fn(1, argv);')
	call v%push('    sy_jit = 0;')
	call v%push('    fflush(stdout);')
	call v%push('')
	call v%push('    /* The tables are in the memory of the program, which is about to be freed */')
	call v%push('    sy_loc_tab = NULL;')
	call v%push('    sy_fn_tab = NULL;')
	call v%push('    return sy_jit_kind;')
	call v%push('}')
	call v%push('')
	call v%push('/* What the last program left: its result, as text, or "" if it had none.  The report')
	call v%push(' * of its runtime error.  The status that it exited with */')
	call v%push('const char *sy_jit_result(void) { return sy_jit_res != NULL ? sy_jit_res : ""; }')
	call v%push('const char *sy_jit_message(void) { return sy_jit_msg != NULL ? sy_jit_msg : ""; }')
	call v%push('int sy_jit_exit_code(void) { return sy_jit_code; }')
	call v%push('float sy_jit_value_f32(void) { return sy_res_val.f; }')
	call v%push('double sy_jit_value_f64(void) { return sy_res_val.d; }')
	call v%push('')
	call v%push('#endif /* SYNTRAN_LLVM */')

end function native_rt_src

