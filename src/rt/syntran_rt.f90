    character(len = *), intent(in) :: joined
    integer, intent(in) :: rank_
    character(len = :), allocatable :: r
    if (rank_ > 1) then
        r = '[' // new_line('a') // joined // new_line('a') // ']'
    else
        r = '[' // joined // ']'
    end if
end function rt_arr_wrap

