! The array [lb: ub], which is empty if ub <= lb
function rt_range_i32(lb, ub) result(r)
    integer(int32), intent(in) :: lb, ub
    integer(int32), allocatable :: r(:)
    integer(int32) :: i
    r = [(i, i = lb, ub - 1_int32)]
end function rt_range_i32

function rt_range_i64(lb, ub) result(r)
    integer(int64), intent(in) :: lb, ub
    integer(int64), allocatable :: r(:)
    integer(int64) :: i
    r = [(i, i = lb, ub - 1_int64)]
end function rt_range_i64

!===============================================================================

! The array [lb: step: ub].  The bound is exclusive and the step may be
! negative.  This is the same algorithm as the interpreter's, including its
! "(i < ub) .eqv. (lb < ub)" loop condition, so that results are identical

function rt_step_i32(lb, step, ub) result(r)
    integer(int32), intent(in) :: lb, step, ub
    integer(int32), allocatable :: r(:)
    integer(int32) :: i
    integer :: j, cap
    if (step == 0) call rt_fatal('array step is 0')
    cap = max(0, (ub - lb + step - sign(1_int32, step)) / step)
    allocate(r(cap))
    j = 1
    i = lb
    if ((lb < ub) .neqv. (0 < step)) i = ub
    do while (((i < ub) .eqv. (lb < ub)) .and. i /= ub)
        r(j) = i
        i = i + step
        j = j + 1
    end do
    r = r(1: j - 1)
end function rt_step_i32

function rt_step_i64(lb, step, ub) result(r)
    integer(int64), intent(in) :: lb, step, ub
    integer(int64), allocatable :: r(:)
    integer(int64) :: i
    integer :: j, cap
    if (step == 0) call rt_fatal('array step is 0')
    cap = int(max(0_int64, (ub - lb + step - sign(1_int64, step)) / step))
    allocate(r(cap))
    j = 1
    i = lb
    if ((lb < ub) .neqv. (0 < step)) i = ub
    do while (((i < ub) .eqv. (lb < ub)) .and. i /= ub)
        r(j) = i
        i = i + step
        j = j + 1
    end do
    r = r(1: j - 1)
end function rt_step_i64

function rt_step_f32(lb, step, ub) result(r)
    real(real32), intent(in) :: lb, step, ub
    real(real32), allocatable :: r(:)
    real(real32) :: f
    integer :: j, cap
    if (.not. (step > 0.0_real32 .or. step < 0.0_real32)) call rt_fatal('array step is 0.0')
    cap = max(0, ceiling((ub - lb) / step))
    allocate(r(cap))
    j = 1
    f = lb
    if ((lb < ub) .neqv. (0 < step)) f = ub
    do while (((f < ub) .eqv. (lb < ub)) .and. (f < ub .or. f > ub))
        r(j) = f
        ! Multiplying instead of repeatedly adding keeps rounding errors from
        ! accumulating, e.g. [0.0: 0.1: 0.9]
        f = lb + j * step
        j = j + 1
    end do
    r = r(1: j - 1)
end function rt_step_f32

function rt_step_f64(lb, step, ub) result(r)
    real(real64), intent(in) :: lb, step, ub
    real(real64), allocatable :: r(:)
    real(real64) :: f
    integer :: j, cap
    if (.not. (step > 0.0_real64 .or. step < 0.0_real64)) call rt_fatal('array step is 0.0')
    cap = max(0, ceiling((ub - lb) / step))
    allocate(r(cap))
    j = 1
    f = lb
    if ((lb < ub) .neqv. (0 < step)) f = ub
    do while (((f < ub) .eqv. (lb < ub)) .and. (f < ub .or. f > ub))
        r(j) = f
        f = lb + j * step
        j = j + 1
    end do
    r = r(1: j - 1)
end function rt_step_f64

!===============================================================================

! The array [lb: ub; n] of n evenly spaced values, including both ends

function rt_linspace_f32(lb, ub, n) result(r)
    real(real32), intent(in) :: lb, ub
    integer(int64), intent(in) :: n
    real(real32), allocatable :: r(:)
    real(real32) :: dx
    integer :: i
    allocate(r(max(0_int64, n)))
    dx = (ub - lb) / real(n - 1)
    do i = 0, int(n) - 1
        r(i + 1) = lb + i * dx
    end do
end function rt_linspace_f32

function rt_linspace_f64(lb, ub, n) result(r)
    real(real64), intent(in) :: lb, ub
    integer(int64), intent(in) :: n
    real(real64), allocatable :: r(:)
    real(real64) :: dx
    integer :: i
    allocate(r(max(0_int64, n)))
    dx = (ub - lb) / real(n - 1, real64)
    do i = 0, int(n) - 1
        r(i + 1) = lb + i * dx
    end do
end function rt_linspace_f64

!===============================================================================

! Join the already-formatted elements of an array of shape `shp`, which are in
! storage (column-major) order.  Elements are separated by ", ".  A rank > 1
! array starts and ends with a line break, and also has one after every
! complete row (and plane, etc.), exactly like the interpreter prints them
function rt_join(items, shp) result(s)
    type(rt_str_t), intent(in) :: items(:)
    integer, intent(in) :: shp(:)
    character(len = :), allocatable :: s

    character(len = :), allocatable :: buf
    integer :: i, j, n, pos, prod, need
    character, parameter :: lf = achar(10)

    n = size(items)
    allocate(character(len = 64) :: buf)
    pos = 0

    call put('[')
    if (size(shp) > 1) call put(lf)

    do i = 1, n
        call put(items(i)%s)
        if (i >= n) cycle
        call put(', ')

        prod = shp(1)
        do j = 2, size(shp)
            if (mod(i, prod) == 0) call put(lf)
            prod = prod * shp(j)
        end do
    end do

    if (size(shp) > 1) call put(lf)
    call put(']')

    s = buf(1: pos)

contains

    ! Append to the buffer, doubling its capacity as needed
    subroutine put(str)
        character(len = *), intent(in) :: str
        character(len = :), allocatable :: tmp
        need = pos + len(str)
        if (need > len(buf)) then
            allocate(character(len = max(need, 2 * len(buf))) :: tmp)
            tmp(1: pos) = buf(1: pos)
            call move_alloc(tmp, buf)
        end if
        buf(pos + 1: need) = str
        pos = need
    end subroutine put

end function rt_join

