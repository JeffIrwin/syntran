! A string as a struct prints it, in double quotes with any quote doubled

function rt_quote(s) result(r)
    character(len = *), intent(in) :: s
    character(len = :), allocatable :: r
    integer :: i
    r = '"'
    do i = 1, len(s)
        if (s(i:i) == '"') r = r // '"'
        r = r // s(i:i)
    end do
    r = r // '"'
end function rt_quote

