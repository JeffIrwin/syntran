! Arrays of strings are built element by element.  Fortran's spread() and
! reshape() copy an array of a type with an allocatable component shallowly, so
! the strings of the result would dangle once the argument is freed

function rt_fill_str(s, n) result(r)
    character(len = *), intent(in) :: s
    integer(int64), intent(in) :: n
    type(rt_str_t), allocatable :: r(:)
    integer(int64) :: i
    allocate(r(max(0_int64, n)))
    do i = 1, n
        r(i)%s = s
    end do
end function rt_fill_str

function rt_reshape_str_2(a, n1, n2) result(r)
    type(rt_str_t), intent(in) :: a(:)
    integer(int64), intent(in) :: n1, n2
    type(rt_str_t), allocatable :: r(:,:)
    integer(int64) :: i, j, k
    if (n1 * n2 /= size(a)) call rt_fatal('array size does not match its shape')
    allocate(r(n1, n2))
    k = 0
    do j = 1, n2
        do i = 1, n1
            k = k + 1
            r(i, j)%s = a(k)%s
        end do
    end do
end function rt_reshape_str_2

function rt_reshape_str_3(a, n1, n2, n3) result(r)
    type(rt_str_t), intent(in) :: a(:)
    integer(int64), intent(in) :: n1, n2, n3
    type(rt_str_t), allocatable :: r(:,:,:)
    integer(int64) :: i, j, l, k
    if (n1 * n2 * n3 /= size(a)) call rt_fatal('array size does not match its shape')
    allocate(r(n1, n2, n3))
    k = 0
    do l = 1, n3
        do j = 1, n2
            do i = 1, n1
                k = k + 1
                r(i, j, l)%s = a(k)%s
            end do
        end do
    end do
end function rt_reshape_str_3

function rt_reshape_str_4(a, n1, n2, n3, n4) result(r)
    type(rt_str_t), intent(in) :: a(:)
    integer(int64), intent(in) :: n1, n2, n3, n4
    type(rt_str_t), allocatable :: r(:,:,:,:)
    integer(int64) :: i, j, l, m, k
    if (n1 * n2 * n3 * n4 /= size(a)) call rt_fatal('array size does not match its shape')
    allocate(r(n1, n2, n3, n4))
    k = 0
    do m = 1, n4
        do l = 1, n3
            do j = 1, n2
                do i = 1, n1
                    k = k + 1
                    r(i, j, l, m)%s = a(k)%s
                end do
            end do
        end do
    end do
end function rt_reshape_str_4

