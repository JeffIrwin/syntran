
! BEGIN INTERNAL
!
! Runtime support for Fortran programs generated by `syntran --transpile`.
!
! This file is embedded at the top of every transpiled program, so it must be
! a self-contained, standard-conforming Fortran module with no dependencies
! other than the Fortran standard library.  Use *spaces* for indentation here,
! unlike the rest of the syntran sources: a tab character is nonstandard in
! free-form Fortran and gfortran warns about it in user programs.
!
! It is also compiled into the syntran library itself, so the compiler checks
! it on every normal build and the unit tests can call it directly.
!
! After editing, regenerate src/transpile_rt.f90 with src/gen_transpile_rt.sh.
! Keep lines under 100 characters.
!
! This block, from BEGIN INTERNAL to END INTERNAL, is for syntran developers,
! so gen_transpile_rt.sh leaves it out of what is embedded.  End users see the
! comment inside the module instead, so keep that one short and free of
! anything about the syntran sources.
!
! Naming: every public name starts with `rt_`.  A name from a syntran program
! that starts the same way gets a `u` in front of it by the transpiler (see
! avoid_runtime_prefix() in transpile_expr.f90), so there are no clashes.  The
! exception is what this module re-exports from iso_fortran_env, which the
! transpiler doesn't let a program's names have either (see reserved_name()).
!
! Layout: a generated program only gets the procedures that it uses, which
! split_units() in transpile.f90 finds by the layout of this file, and
! transpile_rt_units_ok() checks.  So
!
!   - the module's one `contains` is at column 1, before the first procedure
!   - a procedure starts at column 1 with `function` or `subroutine`, possibly
!     after `pure`, `elemental` or `recursive`, so its type is declared in its
!     body, and ends with `end function` or `end subroutine` at column 1.  Its
!     internal procedures are indented
!   - a generic `interface` is indented by 4 spaces, in the module's
!     declarations.  The comment lines right above it come with it
!   - the comment lines above a procedure come with it too, up to the end of
!     the previous procedure
!
! END INTERNAL

!===============================================================================

module syntran_rt

    ! Runtime support for Fortran programs generated by `syntran --transpile`:
    ! printing numbers and arrays the way syntran does, ranges, strings, file
    ! I/O, and so on.  It uses only standard Fortran

    use, intrinsic :: iso_fortran_env, only: int32, int64, real32, real64, output_unit, &
        error_unit, input_unit, iostat_end, iostat_eor
    implicit none

    ! Arrays of strings are arrays of this, because Fortran has no array of
    ! varying-length strings
    type :: rt_str_t
        character(len = :), allocatable :: s
    end type rt_str_t

    ! A file handle.  Like the interpreter's, it is a value: reading from it
    ! updates the variable that it was read through, not other copies
    type :: rt_file_t
        integer :: unit = -1
        character(len = :), allocatable :: name
        logical :: is_open = .false., mode_read = .false., mode_write = .false.
        logical :: eof = .false.
        logical :: is_std = .false.
        ! Opened with "rb" or "wb", so raw bytes instead of lines of text
        logical :: binary = .false.
    end type rt_file_t

    ! Whether reading from stdin has hit the end of input, for the forms of
    ! readln() and eof() with no argument
    logical, save :: rt_stdin_eof = .false.

    ! Convert a scalar to a string exactly like syntran's println()/str() do.
    ! Note that the real kinds are *not* trimmed, for column alignment
    interface rt_str
        module procedure rt_str_bool, rt_str_i32, rt_str_i64, rt_str_f32, rt_str_f64, rt_str_str
    end interface rt_str

    ! Convert an array of rank 1 to 4 to a string, like rt_str() does for a scalar.
    ! These have explicit ranks and call the assumed-rank rt_str_a_<type> below,
    ! because gfortran mishandles an empty array *expression* that is passed
    ! straight to an assumed-rank dummy argument
    interface rt_str_a
        module procedure rt_str_a_bool_1, rt_str_a_bool_2, rt_str_a_bool_3, &
            rt_str_a_bool_4, rt_str_a_i32_1, rt_str_a_i32_2, rt_str_a_i32_3, &
            rt_str_a_i32_4, rt_str_a_i64_1, rt_str_a_i64_2, rt_str_a_i64_3, &
            rt_str_a_i64_4, rt_str_a_f32_1, rt_str_a_f32_2, rt_str_a_f32_3, &
            rt_str_a_f32_4, rt_str_a_f64_1, rt_str_a_f64_2, rt_str_a_f64_3, &
            rt_str_a_f64_4, rt_str_a_str_1, rt_str_a_str_2, rt_str_a_str_3, &
            rt_str_a_str_4
    end interface rt_str_a

    ! Convert an array that is a member of a struct to a string, which also
    ! writes how the type of its elements is given, like `[1'i64, 2'i64]`
    interface rt_str_a_rt
        module procedure rt_str_a_rt_i64, rt_str_a_rt_f32, rt_str_a_rt_str
    end interface rt_str_a_rt

    ! Whole-array equality of two arrays of the same rank, given as shapes and
    ! flattened elements: one bool, false if the shapes differ
    interface rt_arr_eq
        module procedure rt_arr_eq_bool, rt_arr_eq_i32, rt_arr_eq_i64, rt_arr_eq_f32, &
            rt_arr_eq_f64, rt_arr_eq_str
    end interface rt_arr_eq

contains

!===============================================================================

function rt_str_bool(x) result(s)
    logical, intent(in) :: x
    character(len = :), allocatable :: s
    if (x) then
        s = 'true'
    else
        s = 'false'
    end if
end function rt_str_bool

!===============================================================================

function rt_str_i32(x) result(s)
    integer(int32), intent(in) :: x
    character(len = :), allocatable :: s
    character(len = 16) :: buf
    write(buf, '(i0)') x
    s = trim(buf)
end function rt_str_i32

!===============================================================================

function rt_str_i64(x) result(s)
    integer(int64), intent(in) :: x
    character(len = :), allocatable :: s
    character(len = 24) :: buf
    write(buf, '(i0)') x
    s = trim(buf)
end function rt_str_i64

!===============================================================================

function rt_str_f32(x) result(s)
    real(real32), intent(in) :: x
    character(len = :), allocatable :: s
    character(len = 16) :: buf
    write(buf, '(es16.6)') x
    s = buf
end function rt_str_f32

!===============================================================================

function rt_str_f64(x) result(s)
    real(real64), intent(in) :: x
    character(len = :), allocatable :: s
    character(len = 28) :: buf
    write(buf, '(es25.15)') x
    s = buf
end function rt_str_f64

!===============================================================================

function rt_str_str(x) result(s)
    character(len = *), intent(in) :: x
    character(len = :), allocatable :: s
    s = x
end function rt_str_str

!===============================================================================

! Equality of two strings.  Fortran's `==` pads the shorter operand with blanks,
! so "a" == "a " would be true, unlike in syntran
pure function rt_str_eq(a, b) result(eq)
    character(len = *), intent(in) :: a, b
    logical :: eq
    eq = len(a) == len(b)
    if (eq) eq = a == b
end function rt_str_eq

!===============================================================================

! Length-aware lexicographic string less-than.  Fortran's `<` blank-pads the
! shorter operand first, so "a" < "a " would be false.  A string that is a
! strict prefix of another sorts first.  The other orderings derive from this:
!
!     a <= b  =  .not. rt_str_lt(b, a)
!     a >  b  =  rt_str_lt(b, a)
!     a >= b  =  .not. rt_str_lt(a, b)
pure function rt_str_lt(a, b) result(lt)
    character(len = *), intent(in) :: a, b
    logical :: lt
    integer :: i, n
    n = min(len(a), len(b))
    do i = 1, n
        if (a(i:i) /= b(i:i)) then
            lt = a(i:i) < b(i:i)
            return
        end if
    end do
    lt = len(a) < len(b)
end function rt_str_lt

!===============================================================================

! s[i], with a 0-based index.  This is for when the index is an expression which
! mustn't be evaluated twice
function rt_char_at(s, i) result(c)
    character(len = *), intent(in) :: s
    integer(int64), intent(in) :: i
    character(len = 1) :: c
    c = s(i + 1: i + 1)
end function rt_char_at

!===============================================================================

! The 0-based indices of s[lb: step: ub] for a string of length n.  An omitted
! bound depends on the sign of the step, like the interpreter's.  The bound is
! exclusive
function rt_str_step_idx(n, step, lb, ub) result(r)
    integer(int64), intent(in) :: n, step
    integer(int64), intent(in), optional :: lb, ub
    integer(int64), allocatable :: r(:)
    integer(int64) :: lb_, ub_
    if (step == 0) call rt_fatal('subscript step is 0')
    lb_ = 0
    if (step < 0) lb_ = n - 1
    ub_ = n
    if (step < 0) ub_ = -1
    if (present(lb)) lb_ = lb
    if (present(ub)) ub_ = ub
    r = rt_step_i64(lb_, step, ub_)
end function rt_str_step_idx

! s[idx], the characters at the 0-based indices idx, like `s[[0, 3, 5]]`
function rt_str_idx(s, idx) result(r)
    character(len = *), intent(in) :: s
    integer(int64), intent(in) :: idx(:)
    character(len = :), allocatable :: r
    integer :: i
    allocate(character(len = size(idx)) :: r)
    do i = 1, size(idx)
        r(i:i) = s(idx(i) + 1: idx(i) + 1)
    end do
end function rt_str_idx

! s[idx] = rhs.  A repeated index is written more than once, so the last wins
subroutine rt_str_idx_set(s, rhs, idx)
    character(len = *), intent(inout) :: s
    character(len = *), intent(in) :: rhs
    integer(int64), intent(in) :: idx(:)
    integer :: i
    if (size(idx) /= len(rhs)) &
        call rt_fatal('size of RHS does not match size of LHS slice')
    do i = 1, size(idx)
        s(idx(i) + 1: idx(i) + 1) = rhs(i:i)
    end do
end subroutine rt_str_idx_set

! s[lb: step: ub], like a reversed `s[:-1:]`
function rt_str_step(s, step, lb, ub) result(r)
    character(len = *), intent(in) :: s
    integer(int64), intent(in) :: step
    integer(int64), intent(in), optional :: lb, ub
    character(len = :), allocatable :: r
    r = rt_str_idx(s, rt_str_step_idx(int(len(s), int64), step, lb, ub))
end function rt_str_step

! s[lb: step: ub] = rhs
subroutine rt_str_step_set(s, rhs, step, lb, ub)
    character(len = *), intent(inout) :: s
    character(len = *), intent(in) :: rhs
    integer(int64), intent(in) :: step
    integer(int64), intent(in), optional :: lb, ub
    call rt_str_idx_set(s, rhs, rt_str_step_idx(int(len(s), int64), step, lb, ub))
end subroutine rt_str_step_set

!===============================================================================

! println() writes all of its arguments, which the caller has joined, as one line
subroutine rt_println(s)
    character(len = *), intent(in) :: s
    write(output_unit, '(a)') s
end subroutine rt_println

!===============================================================================

! print() is println() without ending the line.  It flushes, so that a prompt
! is shown before a readln() blocks
subroutine rt_print_raw(s)
    character(len = *), intent(in) :: s
    write(output_unit, '(a)', advance = 'no') s
    flush(output_unit)
end subroutine rt_print_raw

!===============================================================================

! exit() says so, then terminates the program with the given status
subroutine rt_exit(code)
    integer(int32), intent(in) :: code
    write(output_unit, *) 'Exiting syntran with status '//rt_str_i32(code)
    flush(output_unit)
    ! `stop code, quiet = .true.` is F2018 and gfortran 10 rejects it, while
    ! plain `stop code` prints a "STOP n" banner
    call exit(code)
end subroutine rt_exit

!===============================================================================

! The CLI prints the value of the program's last statement after it finishes,
! indented with 4 spaces (and a 5th from list-directed output)
subroutine rt_result(s)
    character(len = *), intent(in) :: s
    write(output_unit, *) '    '//s
end subroutine rt_result

!===============================================================================

! A runtime error is fatal.  Compile with -fcheck=all to also catch subscripts
! which are out of bounds
subroutine rt_fatal(msg)
    character(len = *), intent(in) :: msg
    write(error_unit, '(a)') 'Runtime error: '//msg
    error stop 1
end subroutine rt_fatal

!===============================================================================

! Arrays of strings are built element by element.  Fortran's spread() and
! reshape() copy an array of a type with an allocatable component shallowly, so
! the strings of the result would dangle once the argument is freed

function rt_fill_str(s, n) result(r)
    character(len = *), intent(in) :: s
    integer(int64), intent(in) :: n
    type(rt_str_t), allocatable :: r(:)
    integer(int64) :: i
    allocate(r(max(0_int64, n)))
    do i = 1, n
        r(i)%s = s
    end do
end function rt_fill_str

function rt_reshape_str_2(a, n1, n2) result(r)
    type(rt_str_t), intent(in) :: a(:)
    integer(int64), intent(in) :: n1, n2
    type(rt_str_t), allocatable :: r(:,:)
    integer(int64) :: i, j, k
    if (n1 * n2 /= size(a)) call rt_fatal('array size does not match its shape')
    allocate(r(n1, n2))
    k = 0
    do j = 1, n2
        do i = 1, n1
            k = k + 1
            r(i, j)%s = a(k)%s
        end do
    end do
end function rt_reshape_str_2

function rt_reshape_str_3(a, n1, n2, n3) result(r)
    type(rt_str_t), intent(in) :: a(:)
    integer(int64), intent(in) :: n1, n2, n3
    type(rt_str_t), allocatable :: r(:,:,:)
    integer(int64) :: i, j, l, k
    if (n1 * n2 * n3 /= size(a)) call rt_fatal('array size does not match its shape')
    allocate(r(n1, n2, n3))
    k = 0
    do l = 1, n3
        do j = 1, n2
            do i = 1, n1
                k = k + 1
                r(i, j, l)%s = a(k)%s
            end do
        end do
    end do
end function rt_reshape_str_3

function rt_reshape_str_4(a, n1, n2, n3, n4) result(r)
    type(rt_str_t), intent(in) :: a(:)
    integer(int64), intent(in) :: n1, n2, n3, n4
    type(rt_str_t), allocatable :: r(:,:,:,:)
    integer(int64) :: i, j, l, m, k
    if (n1 * n2 * n3 * n4 /= size(a)) call rt_fatal('array size does not match its shape')
    allocate(r(n1, n2, n3, n4))
    k = 0
    do m = 1, n4
        do l = 1, n3
            do j = 1, n2
                do i = 1, n1
                    k = k + 1
                    r(i, j, l, m)%s = a(k)%s
                end do
            end do
        end do
    end do
end function rt_reshape_str_4

