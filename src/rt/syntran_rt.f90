function rt_str_a_bool(x) result(s)
    logical, intent(in) :: x(..)
    character(len = :), allocatable :: s
    select rank (x)
    rank (1)
        s = rt_join(items(x), shape(x))
    rank (2)
        s = rt_join(items(reshape(x, [size(x)])), shape(x))
    rank (3)
        s = rt_join(items(reshape(x, [size(x)])), shape(x))
    rank (4)
        s = rt_join(items(reshape(x, [size(x)])), shape(x))
    rank default
        call rt_fatal('arrays of rank > 4 are not supported by rt_str_a()')
    end select
contains
    function items(a) result(r)
        logical, intent(in) :: a(:)
        type(rt_str_t), allocatable :: r(:)
        integer :: i
        allocate(r(size(a)))
        do i = 1, size(a)
            r(i)%s = rt_str_bool(a(i))
        end do
    end function items
end function rt_str_a_bool

function rt_str_a_i32(x) result(s)
    integer(int32), intent(in) :: x(..)
    character(len = :), allocatable :: s
    select rank (x)
    rank (1)
        s = rt_join(items(x), shape(x))
    rank (2)
        s = rt_join(items(reshape(x, [size(x)])), shape(x))
    rank (3)
        s = rt_join(items(reshape(x, [size(x)])), shape(x))
    rank (4)
        s = rt_join(items(reshape(x, [size(x)])), shape(x))
    rank default
        call rt_fatal('arrays of rank > 4 are not supported by rt_str_a()')
    end select
contains
    function items(a) result(r)
        integer(int32), intent(in) :: a(:)
        type(rt_str_t), allocatable :: r(:)
        integer :: i
        allocate(r(size(a)))
        do i = 1, size(a)
            r(i)%s = rt_str_i32(a(i))
        end do
    end function items
end function rt_str_a_i32

function rt_str_a_i64(x) result(s)
    integer(int64), intent(in) :: x(..)
    character(len = :), allocatable :: s
