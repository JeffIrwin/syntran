function rt_std_file(k) result(f)
    ! std::IN, std::OUT, and std::ERR, which are the 2nd, 3rd, and 4th of the
    ! constants of `std::`
    integer, intent(in) :: k
    type(rt_file_t) :: f
    f%is_open = .true.
    f%is_std = .true.
    select case (k)
    case (2)
        f%name = 'stdin'
        f%unit = input_unit
        f%mode_read = .true.
    case (3)
        f%name = 'stdout'
        f%unit = output_unit
        f%mode_write = .true.
    case default
        f%name = 'stderr'
        f%unit = error_unit
        f%mode_write = .true.
    end select
end function rt_std_file

